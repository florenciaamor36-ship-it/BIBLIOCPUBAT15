// Helper for dates
const today = new Date();
const formatDate = (d: Date) => d.toISOString().split('T')[0];

const dateDaysAgo = (days: number) => {
  const d = new Date(today);
  d.setDate(d.getDate() - days);
  return formatDate(d);
};

const dateDaysAhead = (days: number) => {
  const d = new Date(today);
  d.setDate(d.getDate() + days);
  return formatDate(d);
};

